import * as schema from './schema.js'
import type { BetterSQLite3Database } from 'drizzle-orm/better-sqlite3'
import path from 'path'
import { fileURLToPath } from 'url'

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const DB_TYPE = process.env.DB_TYPE || 'sqlite'

type DrizzleDB = BetterSQLite3Database<typeof schema>
let db: DrizzleDB

if (DB_TYPE === 'postgres') {
  const pg = await import('pg')
  const { drizzle } = await import('drizzle-orm/node-postgres')
  const connectionString = process.env.DATABASE_URL || 'postgresql://postgres:postgres@localhost:5432/huobao_drama'
  const pool = new pg.default.Pool({ connectionString })
  await initPostgresTables(pool)
  db = drizzle(pool, { schema }) as unknown as DrizzleDB
  console.log(`📦 Database: PostgreSQL (${connectionString.replace(/\/\/.*@/, '//***@')})`)
} else {
  const Database = (await import('better-sqlite3')).default
  const { drizzle } = await import('drizzle-orm/better-sqlite3')
  const DB_PATH = process.env.DB_PATH || path.resolve(__dirname, '../../../data/huobao_drama.db')
  const sqlite = new Database(DB_PATH, { timeout: 30000 })
  sqlite.pragma('journal_mode = WAL')
  sqlite.pragma('busy_timeout = 30000')
  initSqliteTables(sqlite)
  db = drizzle(sqlite, { schema })
  console.log(`📦 Database: SQLite (${DB_PATH})`)
}

